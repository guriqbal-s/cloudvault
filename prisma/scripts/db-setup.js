// One-command database bootstrap:  npm run db:setup
//
// Works the same against local PostgreSQL and AWS RDS. It never needs a "shadow database"
// (which `prisma migrate dev` requires and which managed databases often refuse), so the
// database user only needs rights on the CloudVault database itself.
//
//  1. Generate the Prisma client, then check the connection (creating the database if needed).
//  2. If no migration exists yet, write the initial one offline with `prisma migrate diff`
//     (schema.prisma -> SQL, no database involved) and append prisma/extras.sql to it
//     (trigram indexes, partial unique indexes, CHECK constraints).
//  3. Apply pending migrations with `prisma migrate deploy`.
//  4. Seed roles, permissions and the demo dataset.
//
// Safe to re-run: when migrations already exist it only applies pending ones.
// Flags:  --no-seed  skip step 4      --core  seed roles/permissions only (no demo data)

import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..', '..');
const migrationsDir = path.join(repoRoot, 'prisma', 'migrations');
const extrasFile = path.join(repoRoot, 'prisma', 'extras.sql');
const MARKER = '-- CLOUDVAULT_EXTRAS';
const INIT_NAME = '20260101000000_init';

const run = (cmd) => {
  try {
    execSync(cmd, { stdio: 'inherit', cwd: repoRoot });
  } catch {
    console.error(`\nStep failed: ${cmd}\nSee the messages above. For connection problems see docs/aws-rds-setup.md.`);
    process.exit(1);
  }
};
const capture = (cmd) => execSync(cmd, { cwd: repoRoot, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'], maxBuffer: 32 * 1024 * 1024 });

if (!fs.existsSync(path.join(repoRoot, '.env'))) {
  console.error('Missing .env in the repository root. Copy .env.example to .env and set DATABASE_URL first.');
  process.exit(1);
}

console.log('\n> Generating the Prisma client...');
run('npm run db:generate -w backend');

console.log('\n> Checking the database connection...');
run('node prisma/scripts/db-check.js --create');

fs.mkdirSync(migrationsDir, { recursive: true });
const migrationDirs = () =>
  fs.readdirSync(migrationsDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();

if (migrationDirs().length === 0) {
  console.log('\n> Writing the initial migration from schema.prisma...');
  const sql = capture('npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script');
  const dir = path.join(migrationsDir, INIT_NAME);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'migration.sql'), `${sql.trimEnd()}\n\n${MARKER}\n${fs.readFileSync(extrasFile, 'utf8')}`);
  fs.writeFileSync(path.join(migrationsDir, 'migration_lock.toml'),
    '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n');
  console.log(`> Created prisma/migrations/${INIT_NAME}/migration.sql (with prisma/extras.sql appended)`);
}

console.log('\n> Applying migrations...');
run('npm run db:deploy -w backend');

if (!process.argv.includes('--no-seed')) {
  console.log('\n> Seeding...');
  run(`node prisma/seed.js${process.argv.includes('--core') ? ' --core' : ''}`);
}

console.log('\nDatabase ready.');
